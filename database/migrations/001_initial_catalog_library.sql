CREATE TABLE users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE books (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  catalog_source text NOT NULL CHECK (btrim(catalog_source) <> ''),
  source_book_id text NOT NULL CHECK (btrim(source_book_id) <> ''),
  title text NOT NULL CHECK (btrim(title) <> ''),
  author_names text NOT NULL DEFAULT '',
  isbn_10 text,
  isbn_13 text,
  description text,
  cover_url text,
  publication_year smallint CHECK (publication_year BETWEEN 1 AND 3000),
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT books_source_record_unique UNIQUE (catalog_source, source_book_id)
);

CREATE INDEX books_isbn_10_idx ON books (isbn_10) WHERE isbn_10 IS NOT NULL;
CREATE INDEX books_isbn_13_idx ON books (isbn_13) WHERE isbn_13 IS NOT NULL;

CREATE TABLE user_books (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  book_id bigint NOT NULL REFERENCES books (id) ON DELETE RESTRICT,
  status text NOT NULL DEFAULT 'want_to_read'
    CHECK (status IN ('want_to_read', 'reading', 'read', 'did_not_finish')),
  added_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT user_books_owner_book_unique UNIQUE (user_id, book_id)
);

CREATE INDEX user_books_owner_status_added_idx
  ON user_books (user_id, status, added_at DESC);

